#!/usr/bin/env python3
"""Generate dungeon.phext — the Nova Fox demo's tiny shared world.

A real phext: scrolls separated by the scroll break 0x17, per the house
parser (~/workspace/phext/parse_phext.py). Each scroll is one room, drawn
with the OG white-rabbit glyph tables. Rooms are 20 cols x 13 rows and
are built by placing glyphs at coordinates, so placements are exact.

Also emits dungeon.js (the identical text as a JS string) so the demo
page works from file:// without fetch.
"""
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
W, H = 20, 13
SCROLL_BREAK = "\x17"
FLUX = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"  # the 62 flux tokens


class Room:
    def __init__(self):
        self.g = [[" "] * W for _ in range(H)]
        for x in range(W):
            self.g[0][x] = "="
            self.g[H - 1][x] = "="
        for y in range(H):
            self.g[y][0] = "="
            self.g[y][W - 1] = "="

    def put(self, x, y, ch):
        self.g[y][x] = ch
        return self

    def block(self, x, y, w=2, h=2):
        for dy in range(h):
            for dx in range(w):
                self.g[y + dy][x + dx] = "="
        return self

    def hline(self, x0, x1, y, ch):
        for x in range(x0, x1 + 1):
            self.g[y][x] = ch
        return self

    def text(self):
        rows = ["".join(r) for r in self.g]
        assert all(len(r) == W for r in rows) and len(rows) == H
        return "\n".join(rows)


# Room 1 — Arrival. Spawn '/', a scroll portal '_' to room 2, the '*'
# deepening in a fall shaft under the entrance shelf, a '!' clue,
# 2x2 earth blocks, path roads (roads hold you — charted ways are solid).
r1 = Room()
r1.block(3, 3)                      # 2x2 block, upper left
r1.hline(3, 8, 5, ":").put(3, 5, "/")  # entrance shelf (roads)
r1.hline(3, 6, 6, "=")              # shelf support — col 7 stays open:
                                    # the fall shaft, with '*' in it
r1.put(7, 7, "*")
r1.put(9, 2, "!")
r1.hline(8, 10, 3, ":")             # a high road fragment
r1.block(12, 5)
r1.block(13, 7)
r1.block(4, 8)
r1.hline(8, 12, 9, ":")
r1.put(12, 10, ":")
r1.put(13, 11, "_")
ROOM1 = r1.text()

# Room 2 — The Long Shelf. '_' back to room 1, '&' on to room 3,
# '+' life, '%' chance, a lava pit in the floor road and a lava strip
# under the ceiling (flipping gravity here is dangerous — for everyone).
r2 = Room()
r2.put(3, 11, "_").put(6, 11, "+").put(8, 11, "/")
r2.put(11, 11, ".").put(12, 11, ".")
r2.put(14, 11, "%").put(17, 11, "&")
r2.hline(4, 6, 1, ".")              # ceiling lava strip
r2.block(3, 3)
r2.block(15, 4)
r2.hline(7, 11, 5, ":")
r2.block(3, 6)
r2.block(11, 7)
ROOM2 = r2.text()

# Room 3 — Chart Vault. '&' back to room 2, '_' on to room 4, '#' guide,
# '?' save, '$' treasure, a water pool, and the room's native monster
# (monsters are state, not glyphs — it starts at row 11, col 15).
r3 = Room()
r3.put(2, 11, "&").put(4, 11, "#")
r3.hline(7, 9, 11, "~")
r3.put(11, 11, "/").put(12, 11, "?").put(16, 11, "$").put(17, 11, "_")
r3.block(5, 3)
r3.block(15, 3)
r3.hline(9, 12, 5, ":")
r3.block(5, 5)
r3.block(15, 5)
r3.block(8, 7)
r3.put(12, 8, "%")
ROOM3 = r3.text()

# Room 4 — The Quiet Deep. '_' home to room 1, '!' clue, a second '*',
# and a dense flux field in the air (seeded — the spec's "rooms full of
# essentially incompressible noise").
r4 = Room()
r4.put(2, 11, "_").put(5, 11, "/").put(9, 11, "!").put(17, 11, "*")
r4.block(4, 3)
r4.block(12, 4)
r4.put(16, 5, "%")
r4.block(7, 6)
r4.block(14, 8)
rng = random.Random(20261122)
for y in range(1, H - 1):
    for x in range(1, W - 1):
        if r4.g[y][x] == " " and rng.random() < 0.45:
            r4.g[y][x] = rng.choice(FLUX)
ROOM4 = r4.text()

SCROLLS = [ROOM1, ROOM2, ROOM3, ROOM4]
text = SCROLL_BREAK.join(SCROLLS)

(HERE / "dungeon.phext").write_text(text, encoding="utf-8")
(HERE / "dungeon.js").write_text(
    "// GENERATED by gen_dungeon.py from dungeon.phext — identical bytes,\n"
    "// embedded so the demo opens from file:// without fetch.\n"
    f"const DUNGEON_TEXT = {json.dumps(text)};\n",
    encoding="utf-8",
)
print(f"dungeon.phext: {len(text)} bytes, {len(SCROLLS)} scrolls")
